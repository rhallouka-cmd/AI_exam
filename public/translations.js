// Get current language from localStorage or default to English
let currentLanguage = localStorage.getItem('appLanguage') || 'en';

// Set initial language on page load
document.addEventListener('DOMContentLoaded', () => {
  setLanguage(currentLanguage);
  document.documentElement.lang = currentLanguage;
  if (currentLanguage === 'ar') {
    document.documentElement.dir = 'rtl';
    document.body.dir = 'rtl';
  } else {
    document.documentElement.dir = 'ltr';
    document.body.dir = 'ltr';
  }
});

// Function to get translation
function t(key, params = {}) {
  let text = translations[currentLanguage][key] || translations['en'][key] || key;
  
  // Replace parameters in curly braces with values
  Object.keys(params).forEach(param => {
    text = text.replace(`{${param}}`, params[param]);
  });
  
  return text;
}

// Function to set language
function setLanguage(lang) {
  currentLanguage = lang;
  localStorage.setItem('appLanguage', lang);
  document.documentElement.lang = lang;
  
  // Set text direction for Arabic
  if (lang === 'ar') {
    document.documentElement.dir = 'rtl';
    document.body.dir = 'rtl';
  } else {
    document.documentElement.dir = 'ltr';
    document.body.dir = 'ltr';
  }

  // Update all elements with data-i18n attribute
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const attr = el.getAttribute('data-i18n-attr');
    
    if (attr) {
      el.setAttribute(attr, t(key));
    } else {
      el.textContent = t(key);
    }
  });

  // Update elements with data-i18n-key (used when data-i18n-attr needs a different key)
  document.querySelectorAll('[data-i18n-key]').forEach(el => {
    const key = el.getAttribute('data-i18n-key');
    const attr = el.getAttribute('data-i18n-attr');
    
    if (attr && key) {
      el.setAttribute(attr, t(key));
    }
  });

  // Update language selector
  const langSelector = document.getElementById('languageSelector');
  if (langSelector) {
    langSelector.value = lang;
  }

  // Dispatch event for custom translation updates
  window.dispatchEvent(new CustomEvent('languageChanged', { detail: { language: lang } }));
}

// Function to update specific elements
function updateTranslation() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    el.textContent = t(key);
  });
}
